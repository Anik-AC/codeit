async def test_doctor_all_pass(site: FakeSite, client: JiraClient) -> None:
    checks = await run_doctor(client, "CODEIT")
    assert [c.name for c in checks] == ["auth", "project", "statuses", "fields", "transitions"]
    assert all(c.ok for c in checks), checks
    assert "CodeIt Bot" in checks[0].detail


async def test_doctor_bad_auth_stops(mock: respx.MockRouter, client: JiraClient) -> None:
    mock.get("/myself").respond(401)
    checks = await run_doctor(client, "CODEIT")
    assert [(c.name, c.ok) for c in checks] == [("auth", False)]
    assert "JIRA_API_TOKEN" in checks[0].hint


async def test_doctor_unreachable_site(mock: respx.MockRouter, client: JiraClient) -> None:
    mock.get("/myself").mock(side_effect=httpx.ConnectError("dns"))
    checks = await run_doctor(client, "CODEIT")
    assert [(c.name, c.ok) for c in checks] == [("auth", False)]
    assert "JIRA_BASE_URL" in checks[0].hint


async def test_doctor_missing_project_stops(mock: respx.MockRouter, client: JiraClient) -> None:
    mock.get("/myself").respond(json={"displayName": "Bot"})
    mock.get("/project/CODEIT").respond(404)
    checks = await run_doctor(client, "CODEIT")
    assert [(c.name, c.ok) for c in checks] == [("auth", True), ("project", False)]


async def test_doctor_reports_missing_status_and_field(site: FakeSite, client: JiraClient) -> None:
    site.statuses = [s for s in site.statuses if s != "Agent Review"]
    site.story_fields.discard(CUSTOM["Run ID"])
    checks = by_name(await run_doctor(client, "CODEIT"))
    assert not checks["statuses"].ok
    assert "Agent Review" in checks["statuses"].detail
    assert not checks["fields"].ok
    assert "run_id" in checks["fields"].detail
    assert "PRD 7.1" in checks["fields"].hint


async def test_doctor_reports_unreachable_transitions(site: FakeSite, client: JiraClient) -> None:
    site.reachable = ["In Dev"]
    checks = by_name(await run_doctor(client, "CODEIT"))
    assert not checks["transitions"].ok
    assert "Done" in checks["transitions"].detail
    assert "Allow all statuses" in checks["transitions"].hint


async def test_doctor_skips_transitions_without_issues(site: FakeSite, client: JiraClient) -> None:
    site.issues = []
    checks = by_name(await run_doctor(client, "CODEIT"))
    assert checks["transitions"].ok
    assert "skipped" in checks["transitions"].detail


