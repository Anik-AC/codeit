@pytest.fixture
def site(mock: respx.MockRouter) -> FakeSite:
    return FakeSite(mock).install()


def by_name(checks: list[Check]) -> dict[str, Check]:
    return {c.name: c for c in checks}


# discover ---------------------------------------------------------------------------------------


async def test_discover_collects_ids(site: FakeSite, client: JiraClient) -> None:
    ids = await discover(client, "CODEIT")
    assert ids.fields.story_points == "customfield_10016"
    assert ids.fields.agent == CUSTOM["Agent"]  # project-scoped wins over another project's
    assert ids.statuses["Human Review"] == "6"
    assert ids.statuses["Done"] == "7"  # the Story's, not the Epic's
    assert "In Progress" not in ids.statuses
    assert ids.issue_type_id("story") == STORY_ID
    assert ids.transitions["Done"] == "25"


async def test_discover_without_issues_has_no_transitions(
    site: FakeSite, client: JiraClient
) -> None:
    site.issues = []
    ids = await discover(client, "CODEIT")
    assert ids.transitions == {}


async def test_discover_reports_missing_fields(site: FakeSite, client: JiraClient) -> None:
    site.fields = [f for f in site.fields if f["name"] != "PR URL"]
    with pytest.raises(DiscoveryError) as err:
        await discover(client, "CODEIT")
    assert err.value.problems == ["field 'PR URL' not found"]


def test_resolve_fields_ambiguous_and_global_fallback() -> None:
    fields = [
        {"id": "customfield_1", "name": "Story Points"},
        scoped("customfield_2", "Agent"),
        scoped("customfield_3", "Agent"),
        {"id": "customfield_4", "name": "Review Loop"},
    ]
    found, problems = resolve_fields(fields, PROJECT_ID)
    assert found["story_points"] == "customfield_1"
    assert found["review_loop"] == "customfield_4"
    assert "field 'Agent' is ambiguous: customfield_2, customfield_3" in problems


async def test_ids_round_trip_through_yaml(
    site: FakeSite, client: JiraClient, tmp_path: Path
) -> None:
    ids = await discover(client, "CODEIT")
    path = tmp_path / "config" / "jira_ids.yaml"
    write_ids(ids, path)
    assert path.read_text().startswith("# Generated by `codeit jira discover`")
    assert load_ids(path) == ids


def test_load_ids_missing_file(tmp_path: Path) -> None:
    with pytest.raises(FileNotFoundError, match="codeit jira discover"):
        load_ids(tmp_path / "nope.yaml")


